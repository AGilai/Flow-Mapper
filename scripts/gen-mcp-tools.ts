// Generates docs/MCP-TOOLS.md from the registered MCP tools (server/mcp/tools). `npm run docs:mcp` writes it;
// tests/mcp-tools-doc.test.ts fails when the file is stale. Pure function `renderMcpTools()` is shared with the test.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { TOOLS } from '../server/mcp/tools.ts';

/** Task groups, in reading order. Every registered tool must be in exactly one (the test checks). */
export const GROUPS: [string, string[]][] = [
  ['Start and share', ['whoami', 'list_envs', 'create_env', 'share_env', 'set_env_color']],
  ['Design: drafts', ['open_draft', 'list_drafts', 'edit_in_draft', 'draft_changes', 'apply_draft', 'discard_draft']],
  ['Design: from documents', ['import_mermaid', 'import_preview', 'import_into_draft', 'apply_import_plan', 'get_marks', 'edit_design', 'apply_plan_links']],
  ['Design: settings', ['set_subsystem_settings', 'set_levels']],
  ['Read the map', ['search', 'list_services', 'get_service', 'list_entry_points', 'trace_flow', 'find_paths', 'get_endpoint_info', 'get_call', 'get_channel', 'get_exchange', 'get_store', 'list_clients', 'get_resource_keys', 'event_types', 'inventory', 'link_health', 'changelog']],
  ['Subsystems and flows', ['get_subsystems', 'get_subsystem_map', 'list_abstract_links', 'suggest_refinements', 'list_flow_relations', 'get_flow_names', 'set_flow_name', 'set_description']],
  ['Export', ['export_mermaid']],
  ['Collaborate', ['list_comments', 'add_comment', 'resolve_comment', 'get_notes', 'set_notes', 'list_action_items', 'add_action_item', 'update_action_item', 'list_open_questions', 'list_users', 'list_mentions']],
  ['Harvest (sealed envs, harvester token)', ['ingest_manifest', 'load_dtos', 'load_schemas']],
  ['Bugs in Flow-Mapper', ['report_bug', 'list_bugs', 'get_bug', 'update_bug']],
];

const type = (s: any): string => s.enum ? s.enum.map((v: string) => JSON.stringify(v)).join(' | ') : s.type === 'array' ? `${s.items?.type ?? 'any'}[]` : Array.isArray(s.type) ? s.type.join(' | ') : s.type ?? 'any';
const first = (d: string) => { const m = d.match(/^.*?[.](?=\s|$)/s); return (m ? m[0] : d).replace(/\s+/g, ' ').trim().replace(/[.:]$/, '.'); };

export function renderMcpTools(): string {
  const by = new Map(TOOLS.map((t) => [t.name, t]));
  const out = ['# MCP tool catalogue', '', `Generated by \`npm run docs:mcp\` from the ${TOOLS.length} registered tools: do not edit by hand (a test fails when it is stale).`,
    'Start with [AGENTS.md](../AGENTS.md). Every tool that takes `env` requires it: a call without one fails with the list of your environments (there is no default). `*` marks a required argument.', ''];
  for (const [title, names] of GROUPS) {
    out.push(`## ${title}`, '');
    for (const n of names) {
      const t = by.get(n); if (!t) throw new Error(`gen-mcp-tools: group lists unknown tool ${n}`);
      const s: any = t.inputSchema, req = new Set<string>(s.required ?? []);
      const args = Object.entries(s.properties ?? {}).map(([k, v]) => `\`${k}${req.has(k) ? '*' : ''}\` (${type(v)})`).join(', ');
      out.push(`- **\`${n}\`**: ${first(t.description)}${args ? ` Args: ${args}.` : ' No args.'}`);
    }
    out.push('');
  }
  return out.join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) { writeFileSync(new URL('../docs/MCP-TOOLS.md', import.meta.url), renderMcpTools()); console.log('wrote docs/MCP-TOOLS.md'); }
